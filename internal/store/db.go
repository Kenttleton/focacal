package store

import (
	"context"
	"database/sql"
	"fmt"
	"strings"

	_ "modernc.org/sqlite"
)

// DB wraps a *sql.DB with focacal-specific methods.
type DB struct {
	*sql.DB
}

// Compile-time check: *DB must satisfy the Store interface.
var _ Store = (*DB)(nil)

// Open opens (or creates) the SQLite database at path and runs migrations.
func Open(path string) (*DB, error) {
	db, err := sql.Open("sqlite", path+"?_journal_mode=WAL&_foreign_keys=on")
	if err != nil {
		return nil, fmt.Errorf("open sqlite %q: %w", path, err)
	}
	db.SetMaxOpenConns(1) // SQLite: single writer
	if err := migrate(db); err != nil {
		return nil, fmt.Errorf("migrate: %w", err)
	}
	return &DB{db}, nil
}

const schema = `
CREATE TABLE IF NOT EXISTS events (
	id             TEXT PRIMARY KEY,        -- "{source_id}:{calendar_id}:{uid}"
	source_id      TEXT NOT NULL,
	calendar_id    TEXT NOT NULL DEFAULT '',
	uid            TEXT NOT NULL,
	ical_uid       TEXT NOT NULL DEFAULT '',
	title          TEXT NOT NULL DEFAULT '',
	description    TEXT NOT NULL DEFAULT '',
	location       TEXT NOT NULL DEFAULT '',
	start_time     DATETIME NOT NULL,
	end_time       DATETIME NOT NULL,
	all_day        BOOLEAN NOT NULL DEFAULT 0,
	status         TEXT NOT NULL DEFAULT 'confirmed', -- confirmed | tentative | cancelled
	response_status TEXT NOT NULL DEFAULT 'accepted', -- accepted | tentative | declined | needs_action
	show_as        TEXT NOT NULL DEFAULT 'busy',      -- busy | free | oof
	conference_url  TEXT NOT NULL DEFAULT '',
	raw_ical       TEXT NOT NULL DEFAULT '',
	synced_at      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_events_start ON events(start_time);
CREATE INDEX IF NOT EXISTS idx_events_source ON events(source_id);

CREATE TABLE IF NOT EXISTS blocks (
	id           TEXT PRIMARY KEY,        -- UUID generated by planner
	type         TEXT NOT NULL,           -- focus | lunch | break
	title        TEXT NOT NULL,
	start_time   DATETIME NOT NULL,
	end_time     DATETIME NOT NULL,
	priority     INTEGER NOT NULL DEFAULT 0,
	source_event_id TEXT,                 -- set if this block was displaced by a real event
	written_back TEXT NOT NULL DEFAULT '{}', -- JSON map of source_id -> remote_event_id
	created_at   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_blocks_start ON blocks(start_time);

CREATE TABLE IF NOT EXISTS sync_state (
	source_id        TEXT PRIMARY KEY,
	last_synced_at   DATETIME,
	sync_token       TEXT NOT NULL DEFAULT '', -- Google/Outlook incremental sync token
	webhook_id       TEXT NOT NULL DEFAULT '',
	webhook_expiry   DATETIME
);

CREATE TABLE IF NOT EXISTS oauth_tokens (
	source_id    TEXT PRIMARY KEY,
	token_json   TEXT NOT NULL,            -- JSON-encoded oauth2.Token
	updated_at   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS conflict_dismissals (
	key          TEXT PRIMARY KEY,
	dismissed_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
`

// WALCheckpoint runs PRAGMA wal_checkpoint(TRUNCATE) to reclaim WAL file space.
// Call this from a scheduled background goroutine during off-hours.
func (db *DB) WALCheckpoint(ctx context.Context) error {
	_, err := db.ExecContext(ctx, `PRAGMA wal_checkpoint(TRUNCATE)`)
	return err
}

func migrate(db *sql.DB) error {
	// Detect an events table from the old schema (no calendar_id column) and
	// rebuild it, clearing sync tokens so the next sync is a full sync.
	var hasCalendarID bool
	rows, err := db.Query(`PRAGMA table_info(events)`)
	if err == nil {
		for rows.Next() {
			var cid int
			var name, ctype string
			var notnull int
			var dflt interface{}
			var pk int
			if err := rows.Scan(&cid, &name, &ctype, &notnull, &dflt, &pk); err != nil {
				continue
			}
			if name == "calendar_id" {
				hasCalendarID = true
			}
		}
		rows.Close()
	}
	// If the table exists but lacks calendar_id, drop it.
	if !hasCalendarID {
		// only drop if table exists
		var name string
		err := db.QueryRow(`SELECT name FROM sqlite_master WHERE type='table' AND name='events'`).Scan(&name)
		if err == nil {
			if _, err := db.Exec(`DROP TABLE events`); err != nil {
				return fmt.Errorf("drop old events: %w", err)
			}
			if _, err := db.Exec(`UPDATE sync_state SET sync_token = ''`); err != nil {
				return fmt.Errorf("clear sync tokens: %w", err)
			}
		}
	}

	if _, err := db.Exec(schema); err != nil {
		return err
	}
	// Add columns introduced after the initial schema without dropping existing data.
	alters := []string{
		`ALTER TABLE blocks ADD COLUMN locked BOOLEAN NOT NULL DEFAULT 0`,
	}
	for _, stmt := range alters {
		if _, err := db.Exec(stmt); err != nil {
			if !strings.Contains(err.Error(), "duplicate column name") {
				return fmt.Errorf("alter migration: %w", err)
			}
		}
	}
	return migrateVersion(db)
}

// schemaVersion is the current PRAGMA user_version.
const schemaVersion = 2

// migrateVersion runs the versioned one-time steps. Version 2 is the calendar
// model: events and sync_state are keyed by the old source ids, so they are
// caches to rebuild; blocks keep their rows but lose references into them
// (source_event_id, and written_back, which is keyed by source id).
// oauth_tokens are kept. A database created fresh has nothing to reset and
// ends at the current version.
func migrateVersion(db *sql.DB) error {
	var v int
	if err := db.QueryRow(`PRAGMA user_version`).Scan(&v); err != nil {
		return fmt.Errorf("read user_version: %w", err)
	}
	if v >= schemaVersion {
		return nil
	}
	tx, err := db.Begin()
	if err != nil {
		return err
	}
	defer tx.Rollback()
	for _, q := range []string{
		`DELETE FROM events`,
		`DELETE FROM sync_state`,
		`UPDATE blocks SET source_event_id = NULL, written_back = '{}'`,
		fmt.Sprintf(`PRAGMA user_version = %d`, schemaVersion),
	} {
		if _, err := tx.Exec(q); err != nil {
			return fmt.Errorf("schema version %d: %w", schemaVersion, err)
		}
	}
	return tx.Commit()
}
